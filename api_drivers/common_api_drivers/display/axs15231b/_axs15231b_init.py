# The JC3248W535 panel's init: the factory firmware's own sequence for it, read out of its flash image
# (Espressif's esp_lcd AXS15231B driver: MADCTL and the pixel format, then its 28 register writes, then
# normal mode, sleep out, a memory write and display on). straga's SPIBusFast init sends six commands
# and leaves the panel's voltages, timing and gamma at power-on defaults: washed-out greys after a cold
# start. Upstream's longer list has the same registers with other values, and left a brightness step.

