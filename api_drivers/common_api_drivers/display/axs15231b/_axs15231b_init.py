def init(self):
    param_buf = self._param_buf
    param_mv = self._param_mv

    # Colour order and orientation, and the pixel format, as Espressif's driver sends them first.
    param_buf[0] = self._madctl(self._color_byte_order, self._ORIENTATION_TABLE)  # NOQA
    self.set_params(_MADCTL, param_mv[:1])
    param_buf[0] = 0x55 if lv.color_format_get_size(self._color_space) == 2 else 0x66
    self.set_params(_IPF, param_mv[:1])

    for register, parameters in _VENDOR_REGISTERS:  # up to 31 bytes: the framework's param_buf has 4
        self.set_params(register, parameters)

    self.set_params(_BB, bytes(8))
    self.set_params(_NORON)
    self.set_params(_SLPOUT)
    time.sleep_ms(_SLPOUT_MS)  # NOQA
    self.set_params(_RAMWR, bytes(4))
    self.set_params(_DISPON)
